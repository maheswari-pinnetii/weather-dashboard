/**
 * Returns weather data for a given city query when an API key is not configured.
 * Computes deterministic, unique climate conditions based on the city name
 * so every searched city displays its own distinct weather and forecast.
 */
export function getMockWeatherData(cityName: string): WeatherDashboardData {
  const normalized = cityName.trim().toLowerCase();
  for (const [key, val] of Object.entries(mockCitiesData)) {
    if (normalized.includes(key)) {
      return val;
    }
  }

  // Derive unique weather attributes based on the location name string
  let hash = 0;
  for (let i = 0; i < normalized.length; i++) {
    hash = (hash * 31 + normalized.charCodeAt(i)) & 0xffffffff;
  }
  const absHash = Math.abs(hash);

  // Temperature ranges from 12°C to 32°C based on location hash
  const baseTemp = 12 + (absHash % 21);
  const tempMax = baseTemp + 3;
  const tempMin = Math.max(5, baseTemp - 7);
  const humidity = 40 + ((absHash >> 3) % 45);
  const windSpeed = Number((2.0 + ((absHash >> 5) % 60) / 10).toFixed(1));
  const pressure = 1008 + (absHash % 20);

  const weatherConditions = [
    { id: 800, main: 'Clear', description: 'Sunny', icon: '01d' },
    { id: 801, main: 'Clouds', description: 'Partly Cloudy', icon: '02d' },
    { id: 802, main: 'Clouds', description: 'Scattered Clouds', icon: '03d' },
    { id: 500, main: 'Rain', description: 'Light Rain', icon: '10d' },
    { id: 803, main: 'Clouds', description: 'Overcast', icon: '04d' },
  ];
  const primaryWeather = weatherConditions[absHash % weatherConditions.length];

  const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  const forecast = days.map((dayName, idx) => {
    const dayHash = Math.abs((absHash * 17 + idx * 37) & 0xffffffff);
    const dayWeather = weatherConditions[(absHash + idx) % weatherConditions.length];
    const dayMax = tempMax + ((dayHash % 7) - 3);
    const dayMin = Math.max(4, tempMin + ((dayHash % 5) - 2));

    return {
      date: `2025-05-0${idx + 5}`,
      dayName,
      tempMin: dayMin,
      tempMax: dayMax,
      weather: dayWeather,
      precipitationProbability: Number((((dayHash % 60) / 100)).toFixed(2)),
      avgHumidity: Math.min(95, Math.max(30, humidity + ((dayHash % 15) - 7))),
      avgWindSpeed: Number((windSpeed + ((dayHash % 20) - 10) / 10).toFixed(1)),
    };
  });

  const formattedCityName =
    cityName.trim().charAt(0).toUpperCase() + cityName.trim().slice(1);

  return {
    current: {
      cityName: formattedCityName,
      country: '',
      coordinates: {
        lat: Number((((absHash % 1400) - 700) / 10).toFixed(4)),
        lon: Number((((absHash % 3600) - 1800) / 10).toFixed(4)),
      },
      temperature: baseTemp,
      feelsLike: baseTemp + 1,
      tempMin,
      tempMax,
      humidity,
      pressure,
      visibility: 10000,
      windSpeed,
      windDirection: (absHash * 45) % 360,
      weather: primaryWeather,
      timestamp: Math.floor(Date.now() / 1000),
      timezoneOffset: ((absHash % 25) - 12) * 3600,
    },
    forecast,
  };
}
